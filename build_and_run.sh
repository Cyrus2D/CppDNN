#!/bin/bash

# Script de compilação e execução do Sistema Integrado de Bioinformática
# Versão 2.0 - IA Melhorada

echo "=== Sistema Integrado de Bioinformática com Deep Learning ==="
echo "Versão 2.0 - IA Melhorada"
echo "=============================================================="

# Verificar se estamos no diretório correto
if [ ! -f "CMakeLists.txt" ]; then
    echo "Erro: Execute este script no diretório raiz do projeto (onde está o CMakeLists.txt)"
    exit 1
fi

# Função para verificar dependências
check_dependencies() {
    echo "Verificando dependências..."
    
    # Verificar CMake
    if ! command -v cmake &> /dev/null; then
        echo "Erro: CMake não está instalado. Instale com: sudo apt-get install cmake"
        exit 1
    fi
    
    # Verificar compilador C++
    if ! command -v g++ &> /dev/null; then
        echo "Erro: g++ não está instalado. Instale com: sudo apt-get install build-essential"
        exit 1
    fi
    
    # Verificar Eigen3
    if ! pkg-config --exists eigen3; then
        echo "Aviso: Eigen3 pode não estar instalado. Instale com: sudo apt-get install libeigen3-dev"
        echo "Continuando mesmo assim..."
    fi
    
    # Verificar Python (para integração)
    if ! command -v python3 &> /dev/null; then
        echo "Aviso: Python3 não encontrado. Algumas funcionalidades podem não funcionar."
        echo "Instale com: sudo apt-get install python3 python3-pip"
    fi
    
    echo "Verificação de dependências concluída."
}

# Função para compilar o projeto
compile_project() {
    echo "Iniciando compilação..."
    
    # Criar diretório de build se não existir
    if [ ! -d "build" ]; then
        mkdir build
        echo "Diretório build criado."
    fi
    
    # Entrar no diretório build
    cd build
    
    # Configurar com CMake
    echo "Configurando projeto com CMake..."
    if ! cmake .. -DCMAKE_BUILD_TYPE=Release; then
        echo "Erro na configuração do CMake!"
        exit 1
    fi
    
    # Compilar
    echo "Compilando projeto..."
    if ! make -j$(nproc); then
        echo "Erro na compilação!"
        exit 1
    fi
    
    echo "Compilação concluída com sucesso!"
    cd ..
}

# Função para configurar ambiente Python
setup_python_environment() {
    echo "Configurando ambiente Python..."
    
    # Criar diretório dados se não existir
    if [ ! -d "dados" ]; then
        mkdir -p dados/{modelos,treinamento,sequencias,resultados,datasets}
        echo "Estrutura de diretórios criada em ./dados/"
    fi
    
    # Copiar arquivos Python se existirem
    if [ -f "../ia_classi.py" ]; then
        cp ../ia_classi.py dados/
        echo "Arquivo ia_classi.py copiado."
    fi
    
    if [ -f "../sistema_principal.py" ]; then
        cp ../sistema_principal.py dados/
        echo "Arquivo sistema_principal.py copiado."
    fi
    
    # Instalar dependências Python se requirements.txt existir
    if [ -f "requirements.txt" ]; then
        echo "Instalando dependências Python..."
        pip3 install -r requirements.txt --user
    fi
}

# Função para executar exemplos
run_examples() {
    echo "Executando exemplos..."
    
    if [ ! -f "build/bioinformatics_example" ]; then
        echo "Erro: Executável bioinformatics_example não encontrado!"
        echo "Execute primeiro: ./build_and_run.sh --compile"
        exit 1
    fi
    
    # Criar arquivo FASTA de exemplo
    create_example_fasta
    
    # Executar exemplo principal
    echo "--- Executando exemplo de bioinformática ---"
    ./build/bioinformatics_example
    
    echo "Execução concluída!"
}

