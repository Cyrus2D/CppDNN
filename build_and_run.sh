# Função para mostrar ajuda
show_help() {
    echo "Uso: $0 [opções]"
    echo ""
    echo "Opções:"
    echo "  --check-deps    Verificar dependências do sistema"
    echo "  --compile       Compilar o projeto"
    echo "  --setup-python  Configurar ambiente Python"
    echo "  --run           Executar exemplos"
    echo "  --all           Executar tudo (compilar e executar)"
    echo "  --clean         Limpar arquivos de build"
    echo "  --help          Mostrar esta ajuda"
    echo ""
    echo "Exemplos:"
    echo "  $0 --all               # Compilar e executar tudo"
    echo "  $0 --compile --run     # Compilar e depois executar"
    echo "  $0 --check-deps        # Apenas verificar dependências"
}

# Função para limpar build
clean_build() {
    echo "Limpando arquivos de build..."
    if [ -d "build" ]; then
        rm -rf build
        echo "Diretório build removido."
    fi
    
    if [ -d "dados" ]; then
        echo "Deseja remover o diretório dados também? (y/N)"
        read -r response
        if [[ "$response" =~ ^[Yy]$ ]]; then
            rm -rf dados
            echo "Diretório dados removido."
        fi
    fi
    
    echo "Limpeza concluída."
}

# Função principal
